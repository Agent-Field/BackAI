// Generate the plugin manifest and Next.js route proxies.
//
// Scans `apps/dashboard/plugins/<id>/plugin.ts` for plugins (each must default-
// export a `definePlugin({...})` call) and writes:
//
//   1. src/lib/plugins.generated.ts
//      A single module that re-exports the array of plugin manifests, imported
//      from the original plugin.ts source. `loadPlugins()` reads from here.
//
//   2. src/app/(admin)/plugins/<id>/page.tsx
//      A thin proxy file that re-exports the default page component from the
//      plugin's own `page.tsx`. This wires the plugin into the (admin) layout
//      so the sidebar, topbar, auth gate, etc. all apply automatically.
//
// Plugins are inert when the `plugins/` folder is empty: this script writes an
// empty manifest and creates no route proxies.
//
// Run via `pnpm prebuild` / `pnpm predev` (see package.json).

import { existsSync, mkdirSync, readdirSync, statSync, writeFileSync, rmSync } from "node:fs"
import { dirname, join, relative, resolve } from "node:path"
import { fileURLToPath } from "node:url"

const __dirname = dirname(fileURLToPath(import.meta.url))
const DASHBOARD_ROOT = resolve(__dirname, "..")
const PLUGINS_DIR = join(DASHBOARD_ROOT, "plugins")
const GENERATED_MANIFEST = join(
  DASHBOARD_ROOT,
  "src",
  "lib",
  "plugins.generated.ts",
)
const ROUTE_PROXY_ROOT = join(
  DASHBOARD_ROOT,
  "src",
  "app",
  "(admin)",
  "plugins",
)

const BANNER =
  "// AUTO-GENERATED by scripts/generate-plugins-manifest.mjs. Do not edit by hand.\n" +
  "// Run `pnpm prebuild` (or it runs before `pnpm build`) to refresh this file.\n"

function discoverPluginIds() {
  if (!existsSync(PLUGINS_DIR)) return []
  const entries = readdirSync(PLUGINS_DIR)
  const ids = []
  for (const entry of entries) {
    if (entry.startsWith(".") || entry.startsWith("_")) continue
    const dir = join(PLUGINS_DIR, entry)
    let stat
    try {
      stat = statSync(dir)
    } catch {
      continue
    }
    if (!stat.isDirectory()) continue
    const manifest = join(dir, "plugin.ts")
    const page = join(dir, "page.tsx")
    if (!existsSync(manifest)) continue
    if (!existsSync(page)) {
      console.warn(
        `[plugins] Skipping "${entry}": plugin.ts exists but page.tsx is missing.`,
      )
      continue
    }
    ids.push(entry)
  }
  return ids.sort()
}

function relativeImportPath(fromFile, toFile) {
  // Posix-style relative import path, without the `.ts`/`.tsx` extension.
  let p = relative(dirname(fromFile), toFile).split(/[\\/]+/).join("/")
  if (!p.startsWith(".")) p = "./" + p
  return p.replace(/\.(ts|tsx)$/, "")
}

function writeManifest(ids) {
  const importLines = []
  const arrayItems = []
  for (let i = 0; i < ids.length; i++) {
    const id = ids[i]
    const importTarget = join(PLUGINS_DIR, id, "plugin.ts")
    const importPath = relativeImportPath(GENERATED_MANIFEST, importTarget)
    const localName = `plugin_${i}`
    importLines.push(`import ${localName} from "${importPath}"`)
    arrayItems.push(`  ${localName}`)
  }
  const body =
    BANNER +
    "\n" +
    'import type { PluginDefinition } from "./plugins"\n' +
    (importLines.length ? importLines.join("\n") + "\n" : "") +
    "\n" +
    `export const plugins: PluginDefinition[] = [\n${arrayItems.join(",\n")}${arrayItems.length ? ",\n" : ""}]\n`

  mkdirSync(dirname(GENERATED_MANIFEST), { recursive: true })
  writeFileSync(GENERATED_MANIFEST, body)
}

function writeRouteProxies(ids) {
  // Clean any existing proxy directories that no longer correspond to a plugin.
  if (existsSync(ROUTE_PROXY_ROOT)) {
    for (const entry of readdirSync(ROUTE_PROXY_ROOT)) {
      const dir = join(ROUTE_PROXY_ROOT, entry)
      let stat
      try {
        stat = statSync(dir)
      } catch {
        continue
      }
      if (!stat.isDirectory()) continue
      if (!ids.includes(entry)) {
        rmSync(dir, { recursive: true, force: true })
      }
    }
  }

  for (const id of ids) {
    const proxyDir = join(ROUTE_PROXY_ROOT, id)
    const proxyFile = join(proxyDir, "page.tsx")
    const pluginPage = join(PLUGINS_DIR, id, "page.tsx")
    const importPath = relativeImportPath(proxyFile, pluginPage)
    mkdirSync(proxyDir, { recursive: true })
    writeFileSync(
      proxyFile,
      BANNER +
        "\n" +
        `export { default } from "${importPath}"\n`,
    )
  }
}

function main() {
  const ids = discoverPluginIds()
  writeManifest(ids)
  writeRouteProxies(ids)
  if (ids.length === 0) {
    console.log("[plugins] No plugins discovered. Manifest is empty.")
  } else {
    console.log(`[plugins] Discovered: ${ids.join(", ")}`)
  }
}

main()
